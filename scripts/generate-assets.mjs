// scripts/generate-assets.mjs
//
// Inlines the demo HTML pages and the built widget bundle into a TypeScript
// module so the server never has to `import` non-JS assets at runtime.
//
// Why: Node's ESM loader (and therefore Vercel's Node.js runtime) cannot import
// `.html` files — it throws ERR_UNKNOWN_FILE_EXTENSION and crashes the whole
// serverless function. Bundlers like wrangler/esbuild could handle text imports,
// but Vercel's `@vercel/node` builder does not. Generating a plain `.ts` module
// with string exports works identically on Vercel, Node and any bundler.
//
// Regenerate with: npm run gen:assets

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, '..');

const assets = [
  { name: 'WIDGET_JS', file: 'packages/widget/dist/pluggable-bot.js', required: false },
  { name: 'MHT_HTML', file: 'demo/mht-portal.html', required: true },
  { name: 'INDEX_HTML', file: 'demo/index.html', required: true },
  { name: 'VIEW_HTML', file: 'demo/view.html', required: true },
  { name: 'PLUG_HTML', file: 'demo/plug.html', required: true },
  { name: 'MHT_CRAWL_JSON', file: 'data/mht-crawl.json', required: false },
];

let out =
  '// AUTO-GENERATED by scripts/generate-assets.mjs — do not edit by hand.\n' +
  '// Regenerate with: npm run gen:assets\n\n';

for (const asset of assets) {
  const abs = join(root, ...asset.file.split('/'));
  let content = '';

  if (existsSync(abs)) {
    content = readFileSync(abs, 'utf8');
  } else if (asset.required) {
    console.error(`[generate-assets] ERROR: missing required file: ${asset.file}`);
    process.exitCode = 1;
  } else {
    console.warn(`[generate-assets] WARN: missing optional file: ${asset.file} (using empty string)`);
  }

  out += `export const ${asset.name}: string = ${JSON.stringify(content)};\n\n`;
}

const target = join(root, 'packages', 'server', 'src', 'assets.generated.ts');
writeFileSync(target, out, 'utf8');
console.log(`[generate-assets] wrote ${target.replace(root + '\\', '')} (${out.length} bytes)`);
